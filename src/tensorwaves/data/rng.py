"""Implementations of `.RealNumberGenerator`."""

from __future__ import annotations

import secrets
from typing import TYPE_CHECKING

import numpy as np

from tensorwaves.config import _tensorflow_precision
from tensorwaves.function._backend import raise_missing_module_error
from tensorwaves.interface import RealNumberGenerator

if TYPE_CHECKING:  # pragma: no cover
    import tensorflow as tf

    from tensorwaves.data.phasespace import Backend

    SeedLike = int | tf.random.Generator | None


class UniformRNG(RealNumberGenerator):
    """Uniform real random number generator for a selectable computational backend.

    Select the backend with the same string as `.TFPhaseSpaceGenerator`, so that a
    script can switch backends through one variable. The numbers are generated by
    `NumpyUniformRNG`, `TFUniformRealNumberGenerator`, or `JAXUniformRNG`, which is
    available as `implementation`.
    """

    def __init__(self, seed: int | None = None, backend: Backend = "numpy") -> None:
        implementations: dict[str, type[_BackendRNG]] = {
            "jax": JAXUniformRNG,
            "numpy": NumpyUniformRNG,
            "tensorflow": TFUniformRealNumberGenerator,
        }
        if backend not in implementations:
            msg = f'Backend must be one of {sorted(implementations)}, got "{backend}"'
            raise ValueError(msg)
        self.__backend = backend
        self.__implementation = implementations[backend](seed)

    def __call__(
        self, size: int, min_value: float = 0.0, max_value: float = 1.0
    ) -> np.ndarray:
        return self.__implementation(size, min_value, max_value)

    @property
    def backend(self) -> Backend:
        return self.__backend

    @property
    def implementation(self) -> _BackendRNG:
        return self.__implementation

    @property
    def seed(self) -> int | None:
        return self.__implementation.seed

    @seed.setter
    def seed(self, value: int | None) -> None:
        self.__implementation.seed = value


class JAXUniformRNG(RealNumberGenerator):
    """Implements a uniform real random number generator using `JAX <https://docs.jax.dev>`__.

    The generator keeps a `jax.random` key and splits it on every call, so that
    consecutive calls return different numbers.
    """

    def __init__(self, seed: int | None = None) -> None:
        self.seed = seed

    def __call__(
        self, size: int, min_value: float = 0.0, max_value: float = 1.0
    ) -> np.ndarray:
        import jax  # ruff:ignore[import-outside-top-level]

        self.key, call_key = jax.random.split(self.key)
        return jax.random.uniform(  # ty:ignore[invalid-explicit-return]
            call_key, shape=(size,), minval=min_value, maxval=max_value
        )

    @property
    def seed(self) -> int | None:
        return self.__seed

    @seed.setter
    def seed(self, value: int | None) -> None:
        try:
            import jax  # ruff:ignore[import-outside-top-level]
        except ImportError:  # pragma: no cover
            raise_missing_module_error("jax", extras_require="jax")
        self.__seed = value
        if value is None:
            value = secrets.randbits(32)
        self.key = jax.random.key(value)


class NumpyUniformRNG(RealNumberGenerator):
    """Implements a uniform real random number generator using `numpy`."""

    def __init__(self, seed: int | None = None) -> None:
        self.seed = seed

    def __call__(
        self, size: int, min_value: float = 0.0, max_value: float = 1.0
    ) -> np.ndarray:
        return self.generator.uniform(size=size, low=min_value, high=max_value)

    @property
    def seed(self) -> int | None:
        return self.__seed

    @seed.setter
    def seed(self, value: int | None) -> None:
        self.__seed = value
        self.generator: np.random.Generator = np.random.default_rng(seed=self.seed)


class TFUniformRealNumberGenerator(RealNumberGenerator):
    """Implements a uniform real random number generator using tensorflow."""

    def __init__(self, seed: int | None = None) -> None:
        try:
            import tensorflow as tf  # ruff:ignore[import-outside-top-level]
        except ImportError:  # pragma: no cover
            raise_missing_module_error("tensorflow", extras_require="tf")
        self.seed = seed
        self.dtype = tf.float32 if _tensorflow_precision() == "float32" else tf.float64

    def __call__(
        self, size: int, min_value: float = 0.0, max_value: float = 1.0
    ) -> np.ndarray:
        return self.generator.uniform(
            shape=[size],
            minval=min_value,
            maxval=max_value,
            dtype=self.dtype,
        ).numpy()

    @property
    def seed(self) -> int | None:
        return self.__seed

    @seed.setter
    def seed(self, value: int | None) -> None:
        self.__seed = value
        self.generator = _get_tensorflow_rng(self.seed)


_BackendRNG = JAXUniformRNG | NumpyUniformRNG | TFUniformRealNumberGenerator


def _get_tensorflow_rng(seed: SeedLike | None = None) -> tf.random.Generator:
    """Get or create a `tf.random.Generator`.

    https://github.com/zfit/phasespace/blob/5998e2b/phasespace/random.py#L15-L41
    """
    try:
        import tensorflow as tf  # ruff:ignore[import-outside-top-level]
    except ImportError:  # pragma: no cover
        raise_missing_module_error("tensorflow", extras_require="tf")

    if seed is None:
        return tf.random.get_global_generator()
    if isinstance(seed, int):
        return tf.random.Generator.from_seed(seed=seed)
    if isinstance(seed, tf.random.Generator):
        return seed
    msg = f"Cannot create a tf.random.Generator from a {type(seed).__name__}"
    raise TypeError(msg)
